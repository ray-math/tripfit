"""Full gallery/browser regression. No production API, login, or original app."""
from pathlib import Path
import argparse,functools,http.server,threading,json,os
from playwright.sync_api import sync_playwright,expect
ROOT=Path(__file__).resolve().parents[2];OUT=ROOT/'ui-kit/verification';OUT.mkdir(exist_ok=True)
class Quiet(http.server.SimpleHTTPRequestHandler):
 def log_message(self,*args):pass
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
args=argparse.ArgumentParser();args.add_argument('--browser',default='chromium');args.add_argument('--url');options=args.parse_args()
checks=[];errors=[];network=[]
def ck(name,value):
 assert value,name
 checks.append(name)
def load(page,kind='gallery'):
 if options.url:page.goto(options.url,wait_until='networkidle')
 elif os.environ.get('CI'):page.goto(f'http://127.0.0.1:{server.server_port}/ui-kit/dist/{kind}.html',wait_until='networkidle')
 else:page.set_content((ROOT/f'ui-kit/dist/{kind}.html').read_text(),wait_until='load')
 page.wait_for_timeout(800)
with sync_playwright() as p:
 kw={'headless':True}
 if options.browser=='chromium' and Path('/usr/bin/chromium').exists():kw['executable_path']='/usr/bin/chromium'
 browser=getattr(p,options.browser).launch(**kw)
 context=browser.new_context(viewport={'width':393,'height':852},device_scale_factor=2,is_mobile=True,has_touch=True,locale='ko-KR')
 page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)));page.on('request',lambda r:network.append(r.url))
 if not options.url:page.route('https://**/*',lambda r:r.abort())
 load(page)
 ck('35 catalogue entries rendered',page.locator('[data-demo]').count()==35)
 ck('no original application iframe',page.locator('iframe').count()==0)
 ck('no API or original demo data requested',not any('/api/' in u or 'demo_data' in u for u in network))
 page.screenshot(path=str(OUT/f'{options.browser}-gallery-mobile.png'))
 page.locator('[data-filter="asset"]').click();ck('asset filter',page.locator('[data-demo]').count()==6)
 page.get_by_role('searchbox').fill('아이콘');ck('search within filter',page.locator('[data-demo]').count()==1)
 page.get_by_role('searchbox').fill('');page.locator('[data-filter="all"]').click()
 page.locator('[data-demo="chip"]').click();expect(page.get_by_role('dialog')).to_be_visible();page.wait_for_timeout(950)
 ck('real card click opens matching sheet','문장에서' in page.get_by_role('dialog').inner_text())
 page.screenshot(path=str(OUT/f'{options.browser}-gallery-chip.png'))
 page.get_by_role('button',name='상세 창 닫기',exact=True).click();page.wait_for_timeout(350)
 page.evaluate("document.documentElement.dataset.motion='reduce';document.dispatchEvent(new Event('tk:motionchange'))")
 entries=page.evaluate('__gallery.catalog.map(x=>x.id)')
 for entry in entries:
  page.evaluate('(id)=>__gallery.show(id)',entry);page.wait_for_timeout(45)
  ck('opens and renders '+entry,page.locator('#demo-stage').evaluate('(e)=>e.children.length>0'))
  page.locator('#demo-replay').click();page.wait_for_timeout(30)
  page.evaluate('__currentDemo.close()');page.wait_for_timeout(30)
  ck('disposes '+entry,page.evaluate('__gallery.stats().scopes')==0)
 page.evaluate("__gallery.show('list')");page.wait_for_timeout(50)
 page.evaluate("window.__firstListNode=document.querySelector('[data-list-key=\"1\"]')")
 page.locator('#list-reorder').click()
 ck('keyed reorder preserves node identity',page.evaluate("__firstListNode===document.querySelector('[data-list-key=\"1\"]')"))
 ck('keyed list order changed',page.locator('[data-list-key]').first.get_attribute('data-list-key')=='3')
 page.locator('#list-add').click();ck('list addition',page.locator('[data-list-key]').count()==4)
 page.locator('#list-remove').click();page.wait_for_timeout(40);ck('list removal',page.locator('[data-list-key]').count()==3)
 page.evaluate('__currentDemo.close()');page.wait_for_timeout(30)
 page.evaluate("__gallery.show('sheet')");page.wait_for_timeout(50);page.locator('#nested-open').click();page.wait_for_timeout(50)
 ck('two real nested dialog layers',page.locator('[role="dialog"]').count()==2)
 ck('parent sheet is inert while child is open',page.locator('[role="dialog"]').first.evaluate('(e)=>!!e.closest("[inert]")'))
 page.keyboard.press('Tab');ck('tab enters editable field',page.evaluate('document.activeElement.id')=='nested-input')
 page.keyboard.press('Tab');ck('disabled field skipped',page.evaluate('document.activeElement.tagName')=='SUMMARY')
 page.keyboard.press('Escape');page.wait_for_timeout(60)
 ck('escape closes top sheet only',page.locator('[role="dialog"]').count()==1)
 ck('nested close returns focus',page.evaluate('document.activeElement.id')=='nested-open')
 page.keyboard.press('Escape');page.wait_for_timeout(60)
 ck('all inert flags restored',page.locator('.tk-screen > [inert]').count()==0)
 ck('no leaked scopes after nested close',page.evaluate('__gallery.stats().scopes')==0)
 page.evaluate("__gallery.show('hold')");page.wait_for_timeout(40);page.locator('#hold-demo').focus()
 page.keyboard.down('Enter');page.wait_for_timeout(130);page.keyboard.up('Enter')
 ck('short hold cancels',page.locator('#hold-demo').get_attribute('aria-pressed')!='true')
 page.keyboard.down('Enter');page.wait_for_timeout(1080);page.keyboard.up('Enter')
 ck('full hold confirms',page.locator('#hold-demo').get_attribute('aria-pressed')=='true')
 page.evaluate('__currentDemo.close()');page.wait_for_timeout(40)
 page.evaluate("document.documentElement.dataset.motion='auto';document.dispatchEvent(new Event('tk:motionchange'));__gallery.show('spinner')")
 page.wait_for_timeout(200);ck('spinner animates normally',page.evaluate('__gallery.stats().animations')>0)
 page.emulate_media(reduced_motion='reduce')
 # Await the observable media-query and animation state, not a fixed delay.
 page.wait_for_function("matchMedia('(prefers-reduced-motion: reduce)').matches && __gallery.stats().animations === 0",timeout=3000)
 ck('OS reduced motion stops loop',page.evaluate('__gallery.stats().animations')==0 and page.locator('#demo-stage').evaluate("(e)=>!e.getAnimations({subtree:true}).some(a=>a.playState==='running' && a.effect?.getTiming().iterations===Infinity)"))
 page.evaluate('__currentDemo.close()');page.wait_for_timeout(40)
 for w,h in [(320,568),(375,667),(393,852),(430,932),(852,393)]:
  page.set_viewport_size({'width':w,'height':h});page.wait_for_timeout(90)
  ck(f'no gallery overflow {w}x{h}',page.evaluate('document.documentElement.scrollWidth<=innerWidth+1 && document.querySelector(".tk-page").scrollWidth<=document.querySelector(".tk-page").clientWidth+1'))
 ck('no JavaScript exceptions',not errors)
 ck('all scopes disposed at end',page.evaluate('__gallery.stats().scopes')==0)
 context.close()
 desktop=browser.new_page(viewport={'width':1440,'height':1000},locale='ko-KR')
 if not options.url:desktop.route('https://**/*',lambda r:r.abort())
 load(desktop);desktop.screenshot(path=str(OUT/f'{options.browser}-gallery-desktop.png'))
 ck('original 417px desktop frame',desktop.locator('.tk-device').evaluate('(e)=>getComputedStyle(e).width')=='417px')
 desktop.close();browser.close()
server.shutdown()
report={'browser':options.browser,'checks':checks,'passed':len(checks),'errors':errors,'fonts':'network fonts blocked; system fallback verified'}
(OUT/f'{options.browser}-gallery-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
print(json.dumps(report,ensure_ascii=False,indent=2))
